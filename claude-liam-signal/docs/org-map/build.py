def esc(s): return html.escape(s)

def unit_pages(i, u):
    uid, name, cat, what, feeds, hands, status = u
    tag = uid if uid.startswith("E") else ""
    head = f'<div class="eyebrow">{esc(cat)}{(" · " + tag) if tag else ""}</div><h2>{esc(name)}</h2>'
    feeds_html = "".join(f"<li>{esc(x)}</li>" for x in feeds)
    hands_html = "".join(f"<li><b>{esc(to)}</b> ← {esc(w)}</li>" for to, w in hands)
    p1 = f'''
<section class="page unit">
  {head}
  <h3>چیست</h3><p class="what">{esc(what)}</p>
  <div class="two">
    <div><h3>خوراکش از کجا می‌آید</h3><ul>{feeds_html}</ul></div>
    <div><h3>چه چیزی به چه کسی می‌دهد</h3><ul>{hands_html}</ul></div>
  </div>
  <h3>الان در چه وضعی است</h3><p class="status">{esc(status)}</p>
  <div class="foot">{fa(i)} از {fa(len(UNITS))}</div>
</section>'''
    blank = f'''
<section class="page blank">
  <div class="eyebrow">{esc(cat)}{(" · " + tag) if tag else ""}</div>
  <h2>{esc(name)} <span class="muted">— انتظارات حمید</span></h2>
  <div class="lines">{"".join('<div class="ln"></div>' for _ in range(22))}</div>
</section>'''
    return p1 + blank + blank

